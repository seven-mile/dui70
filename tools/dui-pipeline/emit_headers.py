def build_override_votes(inheritance: dict, slot_tables: dict) -> dict:
    """Cross-table override evidence for fold-ambiguous slot binding.

    Returns votes[(name, slot)] = set of classes D such that:
      * D's contract table has a SINGLETON entry `name` at `slot`
        (D's own override — an own-body member at its own slot), and
      * `name` also appears in some OTHER class's fold entry at the
        SAME slot index (i.e. the singleton disambiguates a fold), and
      * D carries the singleton inside a fold-shaped region: the vote
        only applies where the target class's entry at that slot is a
        fold CONTAINING `name`.

    Why this is sound (not a popularity vote): a C++ override may only
    occupy a base slot for the SAME virtual it overrides. A descendant
    D (any class whose table carries the singleton at the same index)
    therefore PINS the identity of that slot's virtual for every class
    whose table shares that slot as a fold containing the name. The
    caller applies a vote only when the target slot's fold contains
    the name, and requires zero contradictions before binding;
    contradictions or absence demote the unit to UNKNOWN (placeholder)
    -- never an alphabetical tie-break.

    Inputs: pinned contracts only (classes.json inheritance +
    vtable-slots.json tables). No generated headers are read.
    """
    votes: dict[tuple[str, int], set] = {}
    # fold membership: name -> slots where SOME class folds it
    fold_slots: dict[str, set[int]] = {}
    for cls, entry in slot_tables.items():
        t = entry.get("slots") if isinstance(entry, dict) else None
        if not isinstance(t, list):
            continue
        for idx, e in enumerate(t):
            if isinstance(e, list) and e:
                for nm in e:
                    fold_slots.setdefault(nm, set()).add(idx)
    for cls, entry in slot_tables.items():
        t = entry.get("slots") if isinstance(entry, dict) else None
        if not isinstance(t, list):
            continue
        for idx, e in enumerate(t):
            if not (isinstance(e, str) and e in fold_slots
                    and idx in fold_slots[e]):
                continue  # singleton that disambiguates nothing
            votes.setdefault((e, idx), set()).add(cls)
    return votes


def _bind_own_units(cls: str, unit_names: list,
                    n_virtuals: dict, slot_lists: list,
                    base_prefix: int = 0,
                    base_names: set | None = None,
                    override_votes: dict | None = None):
    """Bind the class's own virtual-bearing units to vtable slots.

    Returns (name_slot, unbindable, name_slots_actual, slots_of,
             unknown_units):
      name_slot         unit name -> base slot of its virtual run
      unbindable        unit names with no candidate slot (reported, kept
                        in original order; never guessed)
      name_slots_actual unit name -> ALL singleton slots the name occupies
      slots_of          unit name -> chosen slot list (run or split)
      unknown_units     fold-ambiguous units whose binding could NOT be
                        proven by constraints (contradictory or absent
                        override evidence); they are left UNCLAIMED and
                        the walk emits placeholders for their slots
                        (fail-closed UNKNOWN, never a guessed order)

    A unit with k virtuals occupies k CONSECUTIVE slots (an overload run)
    unless it has k distinct singleton slots (a SPLIT run with one body per
    slot, e.g. Edit::CreateHWND at 54/56). Bindings:
      * singleton slots (bare-string entries) bind their names mandatorily;
      * a k-run may sit at base s only if the name appears at every slot
        s..s+k-1 and none of those slots is claimed by another unit;
      * fold-ambiguous units: candidate slots are ordered by cross-table
        OVERRIDE EVIDENCE (build_override_votes) before any positional
        fallback; a unit whose vote evidence is CONTRADICTORY (two names
        vote for the same (unit-set, slot) arrangement) is UNKNOWN;
      * impossible assignments raise with the class/slot list
        (fail-closed).
    """
    n = len(slot_lists)
    appears: dict[str, set[int]] = {}
    for idx, entry in enumerate(slot_lists):
        cands = [entry] if isinstance(entry, str) else list(entry or [])
        for nm in cands:
            if nm in unit_names:
                appears.setdefault(nm, set()).add(idx)
    # a class with a modeled base: a name the base chain does NOT
    # declare is a NEW virtual -- it can only extend the table at
    # slots >= base_prefix (C++ cannot inject it into the inherited
    # region). Base-chain names (overrides) may bind anywhere.
    if base_prefix > 0 and base_names is not None:
        for nm in list(appears):
            if nm not in base_names:
                appears[nm] = {s for s in appears[nm] if s >= base_prefix}
                if not appears[nm]:
                    del appears[nm]

    name_slots: dict[str, list[int]] = {}
    for idx, entry in enumerate(slot_lists):
        if not isinstance(entry, str) or entry not in unit_names:
            continue
        name_slots.setdefault(entry, []).append(idx)

    unbindable = [u for u in unit_names if not appears.get(u)]

    claimed: dict[int, str] = {}

    def unit_slots(name: str, base: int) -> list[int] | None:
        k = n_virtuals.get(name, 1)
        sl = name_slots.get(name)
        if sl and len(sl) >= k:
            # split/over singleton slots: use the lowest k singleton slots
            ss = sorted(sl)[:k]
            if all(claimed.get(s) in (None, name) for s in ss):
                return ss
        if base + k <= n and all(
                base + i in appears.get(name, ()) for i in range(k)):
            ss = list(range(base, base + k))
            if all(claimed.get(s) in (None, name) for s in ss):
                return ss
        return None

    def place(name: str, slots: list[int]) -> None:
        for s in slots:
            claimed[s] = name

    # 0) CONTRADICTION SCAN (override-vote evidence): a unit whose
    #    vote evidence is contradicted -- another unit of this class
    #    also carries a vote for the same slot -- is UNKNOWN: it must
    #    not be bound by vote priority NOR fall back to positional
    #    order. It stays UNCLAIMED; the walk emits placeholders.
    unknown_units: list[str] = []
    if override_votes is not None:
        for u in unit_names:
            if u in unbindable or u in name_slots:
                continue  # singleton-anchored: not fold-ambiguous
            for b in appears.get(u, ()):
                u_has = (u, b) in override_votes
                others = [o for o in unit_names
                          if o != u and (o, b) in override_votes]
                if u_has and others:
                    unknown_units.append(u)
                    break
    unknown_set = set(unknown_units)

    # Slots EVIDENCED for an unknown unit are unprovable for this
    # class when that unit cannot bind: an unknown unit's vote is real
    # evidence that the virtual sits at that slot, so a THIRD unit
    # claiming it by backtracking would fabricate an arrangement the
    # evidence contradicts. Both contested slots (two units voting for
    # the same slot) and exclusively-voted slots (only the unknown unit
    # votes) stay placeholders; slots with no vote evidence remain
    # backtrackable.
    reserved_slots = set()
    if override_votes is not None:
        for u in unknown_units:
            for b in appears.get(u, ()):
                if (u, b) in override_votes:
                    reserved_slots.add(b)
    if reserved_slots:
        appears = {u: {s for s in ss if s not in reserved_slots}
                   for u, ss in appears.items()}
        # (name_slots entries at reserved slots are impossible here:
        # a singleton slot cannot be fold-ambiguous, and unknown units
        # are never singleton-anchored)

    # 1) singleton-anchored units first (their slot is mandatory), then
    #    unanchored units by fewest candidates; ties by name. Anchoring
    #    first prevents a fold-only unit from stealing a run's tail slot
    #    (e.g. Element's _SelfLayoutDoLayout must not take slot 7 away
    #    from the OnPropertyChanged pair anchored at singleton slot 6).
    order = sorted(unit_names, key=lambda u: (
        0 if u in name_slots else 1, len(appears.get(u, ())), u))
    ambiguous: list[str] = []
    for u in order:
        if u in unbindable or u in unknown_set:
            continue
        k = n_virtuals.get(u, 1)
        ss = None
        sl = sorted(name_slots.get(u) or [])
        if sl:
            ss = unit_slots(u, sl[0])
        if ss is None:
            # try every candidate base, OVERRIDE-VOTE evidence first
            # (a descendant's singleton at a shared slot index pins the
            # virtual identity; see build_override_votes). A unit with
            # contradictory vote evidence is UNKNOWN, not guessed.
            cand = sorted(appears.get(u, ()))
            if override_votes is not None:
                # a vote exists when SOME class carries `u` as a
                # singleton at slot b (values are voter classes; the
                # vote's EXISTENCE is the evidence). The vote is only
                # TRUSTED when no OTHER unit of this class also has a
                # vote for the same slot (a split vote is a
                # contradiction -> unit stays for the UNKNOWN path).
                voted = [
                    b for b in cand if (u, b) in override_votes
                    and not any((o, b) in override_votes
                                for o in unit_names if o != u)]
                if voted:
                    cand = sorted(set(voted))
            for b in cand:
                ss = unit_slots(u, b)
                if ss is not None:
                    break
        if ss is not None:
            place(u, ss)
        else:
            ambiguous.append(u)

    # 2) ambiguous units: exact backtracking over free candidate slots.
    #    Candidate order per unit: override-vote evidence first, then
    #    ascending slot index (deterministic).
    ambiguous.sort(key=lambda u: (len(appears.get(u, ())), u))

    def solve(k: int) -> bool:
        if k == len(ambiguous):
            return True
        u = ambiguous[k]
        for b in sorted(appears.get(u, ())):
            ss = unit_slots(u, b)
            if ss is None:
                continue
            place(u, ss)
            if solve(k + 1):
                return True
            for s in ss:
                if claimed.get(s) == u:
                    del claimed[s]
        return False

    if ambiguous and not solve(0):
        raise SystemExit(
            f"contract_reorder: {cls}: cannot bind fold-ambiguous units "
            f"{ambiguous} to distinct free slots "
            f"(candidates={{{', '.join(f'{u}:{sorted(appears.get(u, ()))}' for u in ambiguous[:6])}}}) "
            "-- refusing to guess an order")

    name_slot: dict[str, int] = {}
    slots_of: dict[str, list[int]] = {}
    for u in set(claimed.values()):
        ss = sorted(s for s, uu in claimed.items() if uu == u)
        slots_of[u] = ss
        name_slot[u] = ss[0]
    return name_slot, unbindable, name_slots, slots_of, unknown_units


def contract_reorder(cls: str, members: list, slot_lists: list,
                     base_prefix: int = 0,
                     base_names: set | None = None,
                     override_votes: dict | None = None) -> list:
    """Reorder one class's member declarations into real vtable slot order
    (W5 full-contract v1). `members` is the per-class callable list;
    `slot_lists` is this class's entry from pinned/vtable-slots.json
    (position == slot index; each entry is a name, an ICF fold list, or []).
    Returns the reordered list. Raises SystemExit with a class/slot list if
    an overload run cannot be explained by the contract (fail-closed)."""

    by_name: dict[str, list] = {}
    for s in members:
        by_name.setdefault(s["member"], []).append(s)

    # --- binding: bipartite match own virtual units to distinct slots ----
    n_virtuals: dict[str, int] = {}
    for name, group in by_name.items():
        n_virtuals[name] = sum(1 for s in group if _is_vtable_virtual(s))
    unit_names = [n for n, k in n_virtuals.items() if k > 0]
    name_slot, binder_unbound, name_slots_actual, binder_slots, binder_unknown = _bind_own_units(
        cls, unit_names, n_virtuals, slot_lists,
        base_prefix=base_prefix, base_names=base_names,
        override_votes=override_votes)

    # --- unit construction ----------------------------------------------
    unit_order: dict[str, list] = {}
    set_slots: dict[str, list] = {}   # name -> slots of its VIRTUALS
    unbound: list[str] = []           # virtual-bearing names w/o bound slot
    for name, group in by_name.items():
        virt = [s for s in group if _is_vtable_virtual(s)]
        nonvirt = [s for s in group if not _is_vtable_virtual(s)]
        if not virt:
            unit_order[name] = list(group)
            continue
        s0 = name_slot.get(name)
        if s0 is None:
            # generator synthetic, structurally unbindable (no candidate
            # slot), or fold-UNKNOWN (contradictory/absent override
            # evidence): keep order, report (do NOT guess a slot)
            unbound.append(name)
            unit_order[name] = nonvirt + virt
            continue
        if len(virt) > 1:
            # Overloads normally occupy CONSECUTIVE slots starting at the
            # unit's base (MSVC assigns same-name overloads to adjacent
            # slots in first-declaration order). BUT the binder may have
            # chosen a SPLIT assignment instead -- k singleton slots of
            # this name separated by other members' slots (the real class
            # interleaves the overloads, e.g. Edit::CreateHWND at 54/56
            # with the base-inherited EraseBkgnd at 55). The emitted
            # declaration order must follow the CHOSEN slots, one overload
            # per slot in ascending order; a run is the special case
            # slots = [s0, s0+1, ...]. Measured MSVC rule for adjacent
            # pairs: the CONST first-param overload takes the LOWER slot.
            ss = (list(binder_slots[name])
                  if binder_slots.get(name) and len(binder_slots[name]) == len(virt)
                  else list(range(s0, s0 + len(virt))))
            virt_sorted = sorted(virt, key=lambda s: (
                1 if _first_param_const(s) else 0))
            set_slots[name] = ss
        else:
            virt_sorted = virt
            set_slots[name] = [s0]
        unit_order[name] = nonvirt + virt_sorted

    def _unit_slot(name: str):
        ss = set_slots.get(name)
        return min(ss) if ss else None

    # --- emission -------------------------------------------------------
    # v2: emit an ordered ITEM stream where a placeholder marker
    # ("__PH__<slot>") occupies every real slot that no own unit covers.
    # The header renders placeholders as pure-virtual
    # __DuiAbiSlot_<Class>_<slot>(void) = 0; declarations -- layout-only,
    # never a callable API.
    out: list = []
    emitted: set = set()

    covered = set()
    for n, ss in set_slots.items():
        covered.update(ss)
    # slots provided by a modeled base (the base's table is this table's
    # prefix) are inherited -- the C++ base clause supplies them; never
    # placeholders
    if base_prefix > 0:
        covered.update(range(0, min(base_prefix, len(slot_lists))))

    def _ph(slot: int) -> None:
        out.append(f"__PH__{slot}")

    # --- vdtor unit binding (GENERIC slot rule) ------------------------
    # The destructor set (ctors + dtor + operator=) is a vtable unit like
    # any other: its slot is wherever the contract table carries the
    # vector-deleting-dtor marker `_E<Class>` (MSVC assigns the vdtor the
    # slot of its declaration: first-declared => slot 0, last-declared =>
    # the final slot; both shapes exist in the real binary). The unit is
    # emitted AT that slot during the walk -- the dtor is never assumed
    # to occupy slot 0.
    # Classes with a modeled base: the base clause supplies the inherited
    # region [0, base_prefix); an overriding vdtor marker inside that
    # region is still fine (the declaration overrides the base slot).
    # No marker anywhere + a declared virtual dtor = inexpressible
    # (rejected upstream in contract_classify; fail-closed here too).
    dtor_name: str | None = None
    dtor_slot: int | None = None
    for s in members:
        if classify_dtor(s):
            dtor_name = s["member"]
            break
    if dtor_name is not None:
        for idx, entry in enumerate(slot_lists):
            hit = (entry == f"_E{cls}") or (
                isinstance(entry, list) and f"_E{cls}" in entry)
            if hit:
                dtor_slot = idx
                break
        if dtor_slot is None:
            raise SystemExit(
                f"contract_reorder: {cls}: virtual dtor declared but the "
                f"table has no `_E{cls}` marker -- cannot place the dtor "
                "set; refusing to guess (classify should have rejected)")

    # walk the table slot by slot; at each covered base slot emit the
    # unit (its full run), at each uncovered slot emit a placeholder.
    # Units with a virtual-dtor set occupy the marker slot; other units
    # start at their base slot.
    base_to_units: dict[int, list] = {}
    for n in set_slots:
        b = min(set_slots[n])
        base_to_units.setdefault(b, []).append(n)
    if dtor_slot is not None:
        assert dtor_name is not None
        set_slots[dtor_name] = [dtor_slot]
        base_to_units.setdefault(dtor_slot, []).insert(0, dtor_name)
        # the marker slot is covered by the dtor unit (never a placeholder)
        covered.add(dtor_slot)

    def _is_split(n: str) -> bool:
        ss = set_slots.get(n)
        return bool(ss and len(ss) > 1
                    and ss != list(range(ss[0], ss[0] + len(ss))))

    # split units: slot -> the ONE virtual declared at that slot; the
    # unit's non-virtual members (e.g. a static factory of the same
    # name) lead at the unit's base slot
    split_at: dict[int, list] = {}
    split_lead: dict[str, list] = {}
    for n in set_slots:
        if _is_split(n):
            virt = [s for s in unit_order[n] if _is_vtable_virtual(s)]
            nonvirt = [s for s in unit_order[n] if not _is_vtable_virtual(s)]
            ss = sorted(set_slots[n])
            # virt was sorted const-first; a split's slots are ASCENDING,
            # so pair them in ascending overload order
            for s, sl in zip(virt, ss):
                split_at.setdefault(sl, []).append(s)
            split_lead[n] = nonvirt

    for slot in range(len(slot_lists)):
        if slot in covered:
            for n in sorted(base_to_units.get(slot, []),
                            key=lambda x: x):
                if n in emitted:
                    continue
                if _is_split(n):
                    # non-virtual same-name members lead, then the
                    # virtual for THIS slot; remaining overloads follow
                    # at their own slots below
                    for extra in split_lead.get(n, []):
                        out.append(extra)
                    for s in split_at.get(slot, []):
                        out.append(s)
                    emitted.add(n)
                else:
                    out.extend(unit_order[n])
                    emitted.add(n)
            # split-unit overloads whose own slot carries no base unit
            for s in split_at.get(slot, []):
                if s not in out:
                    out.append(s)
        else:
            _ph(slot)

    # any unit whose base wasn't reached (shouldn't happen; fail closed)
    leftover = [n for n in set_slots if n not in emitted]
    if leftover:
        raise SystemExit(
            f"contract_reorder: {cls}: units never emitted: {leftover[:6]}")

    # unbound virtual-bearing units next (stable, original order).
    # Two populations reach here:
    #   * generator synthetics (On*Virt etc.) -- pipeline bugs; and
    #   * fold-UNKNOWN units (contradictory/absent override evidence):
    #     their slots became placeholders ABOVE (covered never includes
    #     them), and the unit's virtuals are appended here in original
    #     order so the header still declares them (an unbound
    #     declaration does not enter the vtable walk). This is the
    #     fail-closed UNKNOWN path: never a guessed slot.
    if unbound:
        synth = [n for n in unbound if n not in binder_unknown]
        if synth:
            raise SystemExit(
                f"contract_reorder: {cls}: v2 classified bound but "
                f"{len(synth)} unit(s) have no candidate slot: "
                f"{synth[:6]} -- refuse to emit")

    # remaining pure-nonvirtual sets, access-grouped, original order
    for acc in ("public", "protected", "private"):
        for s in members:
            if s["member"] in emitted or access_of(s) != acc:
                continue
            out.extend(unit_order[s["member"]])
            emitted.add(s["member"])

    n_members = sum(1 for x in out if not isinstance(x, str))
    assert n_members == len(members), (cls, n_members, len(members))
    assert {id(x) for x in out if not isinstance(x, str)} == {id(x) for x in members}
    return out


def contract_classify(cls: str, members: list, slot_lists: list,
                      exported_virtuals: set,
                      base_prefix: int = 0,
                      base_names: set | None = None,
                      override_votes: dict | None = None) -> dict:
    """v2 classification for one class against its contract table.

    Returns one of:
      {"mode": "bound", ...}        own units bound; placeholders fill the
                                    remaining real slots
      {"mode": "rejected", ...}     C++ cannot express the real layout with
                                    this pipeline's model; the class is
                                    emitted in canonical order and listed
                                    (never silently)
    Rejection reasons (checked in order):
      external_virtuals   the class exports virtuals that are not in its
                          primary table (they live in secondary/MI
                          subobject tables this pipeline does not model)
      vdtor_unplaced      the class declares a virtual destructor but the
                          table carries no `_E<Class>` marker anywhere:
                          no slot can express the dtor
    IClassInfo/ClassInfoBase is deliberately excluded from vdtor placement
    rejection: it is the L2 problem (tracked separately, not masked here).
    """
    if cls == "ClassInfoBase":
        # L2 (IClassInfo slot0 +1 layout) is tracked as a SEPARATE
        # subproblem: not placeholder-masked, not vdtor-rejected. It keeps
        # canonical order with an explicit L2 banner.
        return {"mode": "l2"}

    tabnames: set = set()
    for s in slot_lists:
        tabnames |= ({s} if isinstance(s, str) else set(s))
    ext = sorted(x for x in (exported_virtuals or set())
                 if x != cls and x not in tabnames)
    if ext:
        return {"mode": "rejected", "reason": "external_virtuals",
                "external": ext}

    # vdtor placement (GENERIC rule): the destructor set binds to the
    # slot carrying the `_E<Class>` marker WHEREVER it sits (slot 0 when
    # the dtor was declared first, the last slot when declared last --
    # both shapes exist in the real binary). A virtual dtor is only
    # inexpressible when the table carries NO marker at all.
    has_vdtor_decl = any(classify_dtor(s) for s in members)
    if has_vdtor_decl:
        marker = next((
            i for i, entry in enumerate(slot_lists)
            if entry == f"_E{cls}" or (
                isinstance(entry, list) and f"_E{cls}" in entry)), None)
        if marker is None:
            return {"mode": "rejected", "reason": "vdtor_unplaced",
                    "slots": len(slot_lists)}
        covered_dtor = {marker}
    else:
        covered_dtor = set()

    # bound: compute which slots the own units cover
    by_name: dict[str, list] = {}
    for s in members:
        by_name.setdefault(s["member"], []).append(s)
    n_virtuals = {n: sum(1 for s in g if _is_vtable_virtual(s))
                  for n, g in by_name.items()}
    unit_names = [n for n, k in n_virtuals.items() if k > 0]
    name_slot, unbindable, name_slots_actual, binder_slots, _unknown = _bind_own_units(
        cls, unit_names, n_virtuals, slot_lists,
        base_prefix=base_prefix, base_names=base_names,
        override_votes=override_votes)
    covered = set()
    for n, s0v in name_slot.items():
        # use the CHOSEN slot set (a split unit covers exactly its k
        # singleton slots, not the run s0..s0+k-1)
        k = n_virtuals.get(n, 1)
        ss = (list(binder_slots[n])
              if binder_slots.get(n) and len(binder_slots[n]) == k
              else list(range(s0v, s0v + k)))
        covered.update(ss)
    covered |= covered_dtor
    # slots provided by a modeled base (its own table is the prefix of
    # this class's table) are INHERITED -- never placeholders
    if base_prefix > 0:
        covered.update(range(0, min(base_prefix, len(slot_lists))))
    placeholders = [i for i in range(len(slot_lists))
                    if i not in covered]
    return {"mode": "bound", "name_slot": name_slot,
            "unbindable": unbindable,
            "placeholders": sorted(placeholders),
            "slots": len(slot_lists)}


def contract_report(cls: str, members: list, slot_lists: list) -> dict:
    """Binding statistics for the generation report (which classes are
    fully contract-bound, which carry unbindable virtuals)."""
    slot_of: set = set()
    for idx, entry in enumerate(slot_lists):
        if idx == 0:
            continue
        cands = [entry] if isinstance(entry, str) else list(entry or [])
        slot_of.update(cands)
    bound = unbound = 0
    unbound_names: list = []
    for s in members:
        if not _is_vtable_virtual(s):
            continue
        if s["member"] in slot_of:
            bound += 1
        else:
            unbound += 1
            if s["member"] not in unbound_names:
                unbound_names.append(s["member"])
    return {"class": cls, "bound": bound, "unbound": unbound,
            "unbound_names": unbound_names,
            "slots": len(slot_lists)}


# --- migration assertion: the contract-derived Element virtual set must
# equal the audited pilot evidence table (kept as data only, see above).
def assert_element_pilot_migration(cls: str, members: list,
                                   slot_lists: list) -> None:
    if cls != "Element":
        return
    names = [s["member"] for s in members if _is_vtable_virtual(s)]
    derived: list = []
    seen: set = set()
    for idx, entry in enumerate(slot_lists):
        if idx == 0:
            continue
        cands = [entry] if isinstance(entry, str) else list(entry or [])
        for nm in names:
            if nm in cands and nm not in seen:
                seen.add(nm)
                derived.append(nm)
    audited = sorted(set(ELEMENT_PILOT_SLOT_ORDER))
    if sorted(set(derived)) != audited:
        raise SystemExit(
            "migration assertion: contract-derived Element virtual set "
            "diverged from the audited pilot table "
            f"(contract-only={sorted(set(derived) - set(audited))} "
            f"audited-only={sorted(set(audited) - set(derived))})")


