    lines.append("        virtual bool IsValidProperty(PropertyInfo const*) = 0;        // 9")
    lines.append("        virtual bool IsSubclassOf(IClassInfo*) = 0;                   // 10")
    lines.append("        virtual void Destroy(void) = 0;                               // 11")
    lines.append("        virtual HINSTANCE GetModule(void) = 0;                        // 12")
    lines.append("        virtual bool IsGlobal(void) = 0;                              // 13")
    lines.append("        virtual void AddChild(void) = 0;                              // 14")
    lines.append("        virtual void RemoveChild(void) = 0;                           // 15")
    lines.append("        virtual unsigned int GetChildren(void) = 0;                   // 16")
    lines.append("        virtual void AssertPIZeroRef(void) = 0;                       // 17")
    lines.append("    };")
    lines.append("")
    lines.append("    // IXProviderCP / IXElementCP are REAL exported classes now --")
    lines.append("    // see their generated headers (IXProviderCP.h / IXElementCP.h).")
    lines.append("")
    lines.append("    // IXProvider: the abstract interface XProvider implements.")
    lines.append("    // Slot order: IUnknown first (QI/AddRef/Release), then the")
    lines.append("    // provider methods in DirectUI order. On x64 the real methods")
    lines.append("    // are all __cdecl; the __stdcall markers in the DirectUI headers are")
    lines.append("    // ignored by the x64 compiler, so we use the default here too.")
    lines.append("    //")
    lines.append("    // MIDL_INTERFACE semantics (struct + novtable + protected ctor with")
    lines.append("    // NO definition): a pure abstract interface must not EMIT any")
    lines.append("    // symbol. Without novtable the compiler synthesizes ??_7IXProvider")
    lines.append("    // (vftable) for the base subobject that XProvider's ctor")
    lines.append("    // initializes; with an implicit public ctor it emits")
