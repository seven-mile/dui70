    lines.append("        // slots follow the DirectUI order (AddRef..AssertPIZeroRef,")
    lines.append("        // then the deleting dtor)")
    lines.append("        virtual long AddRef(void) = 0;                                   // 0")
    lines.append("        virtual long Release(void) = 0;                                 // 1")
