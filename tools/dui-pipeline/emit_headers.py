def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--pinned", type=Path, default=DEFAULT_PINNED)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--classes", default=None,
                    help="override the class list from classes.json (comma-separated)")
    args = ap.parse_args(argv)

    # class list + inheritance from pinned/classes.json (axis B made explicit)
    classes, inheritance = load_classes(args.pinned / "classes.json")
    if args.classes:
        classes = [c.strip() for c in args.classes.split(",") if c.strip()]

    out_dir: Path = args.out
    out_dir.mkdir(parents=True, exist_ok=True)

    # pin fingerprint for the banner
    manifest = json.loads((args.pinned / "manifest.json").read_text(encoding="utf-8"))
    pin_hash12 = manifest["dll"]["sha256"][:12]
    banner = make_banner(pin_hash12)

    symbols = load_symbols(args.pinned / "symbols.json")
    tr = TypeTranslator(classes)

    # W5 full-contract v1: the vtable slot-order ground truth. The table is
    # a pure function of the DLL bytes + symbols.json (extract-vtable-
    # slots.py), re-derived and byte-compared by repro.py gate R3' -- the
    # emitter CONSUMES it, never duplicates it. Missing table = error: a
    # silent fallback to alphabetical order would reintroduce W5.
    slots_doc_path = args.pinned / "vtable-slots.json"
    if not slots_doc_path.is_file():
        print("emit_headers: ERROR  pinned/vtable-slots.json missing "
              "(the W5 contract); refusing to emit alphabetical order",
              file=sys.stderr)
        return 2
    slots_doc = json.loads(slots_doc_path.read_text(encoding="utf-8"))
    slot_tables = slots_doc.get("classes") or {}
    global slot_tables_global
    slot_tables_global = slot_tables

    # Cross-table override evidence for fold-ambiguous slot binding
    # (derived ONLY from the pinned contracts: vtable-slots.json tables;
    # a descendant's singleton entry at a shared slot index pins the
    # virtual's identity -- see build_override_votes). Alphabetical /
    # leftmost tie-breaks are no longer trusted for fold pairs.
    override_votes = build_override_votes(inheritance, slot_tables)
    n_votes = sum(len(v) for v in override_votes.values())

    # W5 stage-2 schema-2 MI tables (optional): provider-family classes
    # with verified three-table MI layout leave the rejected path and
    # are emitted with interface-order slot identity. Membership is
    # decided from the pinned data alone (mi_provider_shape); the
    # interface-length manual inputs are part of pinned (G1-locked).
    mi_doc = load_mi_tables(args.pinned)
    global _MI_DOC_LOADED
    _MI_DOC_LOADED = mi_doc is not None
    mi_build_template_id_maps(symbols)
    mi_shapes: dict[str, dict] = {}
    mi_template_shapes: dict[str, dict] = {}
    if mi_doc is not None:
        for mi_key, entry in (mi_doc.get("derived") or {}).items():
            if mi_key.startswith("?$PatternProvider@"):
                # template instantiation: keyed by its mangled name in
                # schema 2; translate to the classes.json display name
                cls = mi_template_display_name(mi_key)
                if cls is None or cls not in classes:
                    continue
                # the template has no primary table of its own (the
                # interface's pure methods keep it abstract; the
                # concrete class owns the primary). Its SECONDARIES
                # must match the family shape: RefcountBase secondary
                # exactly [dtor-marker, Init] with manual provenance
                # (the manual interface-length input), IProvider
                # secondary length manual with a fold entry that
                # CONTAINS GetProxyCreator (the template's generic body
                # is ICF-folded across many classes).
                secs = entry.get("secondaries") or {}
                ip = secs.get("IProvider")
                rb = secs.get("RefcountBase")
                if not (isinstance(ip, dict) and isinstance(rb, dict)):
                    continue
                ip_slots = ip.get("slots")
                ip_fold = (ip_slots[0] if isinstance(ip_slots, list)
                           and ip_slots and isinstance(ip_slots[0], list)
                           else None)
                rb_slots = rb.get("slots")
                if (ip.get("length_provenance") == "manual"
                        and rb.get("length_provenance") == "manual"
                        and ip_fold and "GetProxyCreator" in ip_fold
                        and isinstance(rb_slots, list) and len(rb_slots) == 2
                        and rb_slots[1] == "Init"):
                    m = re.match(
                        r"PatternProvider<class DirectUI::(\w+),", cls)
                    mi_template_shapes[cls] = {
                        "pattern_methods": [],
                        "_concrete": m.group(1) if m else "_Unknown",
                    }
            else:
                cls = mi_key
                if cls not in classes:
                    continue
                shape = mi_provider_shape(entry)
                if shape is not None:
                    mi_shapes[cls] = shape
                    continue
                # the 14th native UIA provider family
                # (HWNDElementProvider): primary =
                # IRawElementProviderFragmentRoot + 4 secondaries
                shape = hwnd_provider_shape(entry)
                if shape is not None:
                    mi_shapes[cls] = shape
        n_mi = len(mi_shapes) + len(mi_template_shapes)
        print(f"emit_headers: schema-2 MI tables loaded "
              f"({len(mi_doc.get('derived') or {})} classes; "
              f"{n_mi} qualify for provider-MI emission "
              f"({len(mi_shapes)} concrete + {len(mi_template_shapes)} "
              f"templates)")

    stats = {}
    contract_rows = []
    v2_rows = []
    # class -> exported virtual member names (for base-declared checks)
    exp_virt_by_class: dict = {}
    for s in symbols:
        if s.get("is_virtual") and s.get("is_exported") and s.get("class"):
            exp_virt_by_class.setdefault(s["class"], set()).add(s["member"])
    for cls in classes:
        if is_duixml_nested(cls):
            # nested in DUIXmlParser: emitted by its header/TU, not standalone
            continue
        if is_nested_pseudo_class(cls):
            # nested in a host class (e.g. AccessibleButton::ACCESSIBLEROLE):
            # declared inside the host's header, no standalone file
            continue
        if cls in mi_template_shapes:
            # schema-2 MI: the PatternProvider specialization is emitted
            # by its concrete provider's MI path (with the interface
            # header); the legacy template-specialization path is
            # bypassed so the two never collide.
            continue
        members = [s for s in symbols
                   if s.get("class") == cls
                   and s.get("is_exported")
                   and in_directui_scope(s)
                   and is_callable(s)]
        if (cls == "IProvider" and mi_doc_loaded()
                and cls in POLYMORPHIC_BASE_CLASSES):
            # W5 stage-2: IProvider's PDB members (ctor/assign folds)
            # are ICF artifacts; the schema-2 interface block declares
            # them (private, stub-TU defined) instead of the walk.
            members = []
        data_members = [s for s in symbols
                        if s.get("class") == cls
                        and s.get("is_exported")
                        and in_directui_scope(s)
                        and is_data(s)]
        has_own_vftable = any(
            (s.get("mangled") or "").endswith(f"??_7{cls}@DirectUI@@6B@")
            for s in symbols
            if s.get("class") == cls and s.get("is_exported")
        )
        entry = slot_tables.get(cls)
        slot_lists = entry.get("slots") if isinstance(entry, dict) else None
        if slot_lists is not None and not isinstance(slot_lists, list):
            print(f"emit_headers: ERROR  contract entry for {cls} is not a "
                  "slot list", file=sys.stderr)
            return 2
        mi_shape = mi_shapes.get(cls)
        if mi_shape is not None:
            # schema-2 MI emission: slot identity is carried by interface
            # declaration order; the contract walk is bypassed entirely
            # (classification would reject these classes -- their exported
            # virtuals live across three tables, which is exactly what the
            # MI path expresses).
            content = render_class_header(
                cls, members, data_members, tr, classes, inheritance,
                banner, has_own_vftable=has_own_vftable,
                slot_lists=None, base_prefix=0,
                exported_virtuals_by_class=exp_virt_by_class,
                override_votes=override_votes, mi_shape=mi_shape)
            (out_dir / f"{safe_name(cls)}.h").write_text(
                content, encoding="utf-8", newline="\n")
            if "primary_iface" in mi_shape:
                # HWNDElementProvider family: the primary interface is a
                # REAL SDK interface (UIAutomationCore.h owns it under
                # Option D) and there is no PatternProvider intermediate
                # -- no generated interface/template headers
                stats[cls] = {"methods": len(members),
                              "data": len(data_members), "mi": True}
                continue
            # the pattern interface header (primary-table slot order)
            iface = mi_pattern_iface_name(cls)
            iface_content = render_mi_pattern_iface_header(
                iface, cls, members, tr, banner, mi_shape)
            (out_dir / f"{iface}.h").write_text(
                iface_content, encoding="utf-8", newline="\n")
            # the PatternProvider specialization (the real intermediate
            # base: carries Init + the generic GetProxyCreator slots)
            tpl_id = mi_template_class_id(cls, classes)
            if tpl_id is not None and tpl_id in mi_template_shapes:
                tpl_members = [s for s in symbols
                               if s.get("class") == tpl_id
                               and s.get("is_exported")
                               and in_directui_scope(s)
                               and is_callable(s)]
                tpl_content = render_mi_template_header(
                    tpl_id, tpl_members, [], tr, classes, banner,
                    mi_template_shapes[tpl_id], iface)
                (out_dir / f"{safe_name(tpl_id)}.h").write_text(
                    tpl_content, encoding="utf-8", newline="\n")
            stats[cls] = {"methods": len(members),
                          "data": len(data_members), "mi": True}
            continue
        # v2 exported-virtual set for classification (from symbols.json,
        # the canonical source -- not a hand table)
        cls_exp_virt = {s["member"] for s in symbols
                        if s.get("class") == cls and s.get("is_virtual")
                        and s.get("is_exported")}
        cls_exp_virt.discard(cls)
        classification = None
        base_prefix = 0
        base_names = None
        if slot_lists is not None:
            for b in base_list(inheritance, cls):
                be = slot_tables.get(b)
                if isinstance(be, dict) and isinstance(be.get("slots"), list):
                    base_prefix = max(base_prefix, len(be["slots"]))
            # SAME base-name set the renderer uses (single source:
            # base_chain_virtual_names) -- classification stats and the
            # emitted header must agree by construction, not by accident.
            if base_prefix:
                base_names = base_chain_virtual_names(
                    cls, inheritance, exp_virt_by_class)
            classification = contract_classify(
                cls, members, slot_lists, cls_exp_virt,
                base_prefix=base_prefix or 0, base_names=base_names,
                override_votes=override_votes)
        content = render_class_header(cls, members, data_members, tr,
                                      classes, inheritance, banner,
                                      has_own_vftable=has_own_vftable,
                                      slot_lists=slot_lists,
                                      base_prefix=base_prefix,
                                      exported_virtuals_by_class=exp_virt_by_class,
                                      base_names=base_names,
                                      override_votes=override_votes)
        (out_dir / f"{safe_name(cls)}.h").write_text(content, encoding="utf-8", newline="\n")
        stats[cls] = {"methods": len(members), "data": len(data_members)}
        if slot_lists is not None:
            contract_rows.append(
                contract_report(cls, members, slot_lists))
            if classification and classification["mode"] == "bound":
                v2_rows.append(dict(classification, cls=cls))
            elif classification:
                v2_rows.append(dict(classification, cls=cls))

    # shared prelude + interfaces + aggregate
    (out_dir / "dui_abi_types.h").write_text(render_abi_types_header(banner), encoding="utf-8", newline="\n")
    (out_dir / "Interfaces.h").write_text(render_interfaces_header(banner), encoding="utf-8", newline="\n")
    (out_dir / "DirectUI.h").write_text(render_aggregate_header(classes, banner), encoding="utf-8", newline="\n")

    # ---- artifact consistency (fail-closed) ---------------------------
    # The classification report and the emitted headers are two views of
    # ONE classification; a placeholder must exist in the rendered file
    # if and only if the classification counted it. Counting from the
    # artifacts themselves (not the in-memory classification) catches any
    # drift between the walk emission and the stats.
    hdr_ph_by_class: dict[str, int] = {}
    phre = re.compile(r"virtual void (__DuiAbiSlot_(\w+)_(\d+))\(void\) = 0;")
    for hf in sorted(out_dir.glob("*.h")):
        phc = len(phre.findall(hf.read_text(encoding="utf-8")))
        if phc:
            hdr_ph_by_class[hf.stem] = phc
    cls_ph_by_class = {r["cls"]: len(r["placeholders"])
                       for r in v2_rows if r["mode"] == "bound"
                       and r.get("placeholders")}
    # MI pattern-interface headers carry fold placeholders by design
    # (fold entries emit ABI placeholders -- no first-appearance pick).
    # The expected count per iface = its mi_shape fold entries (the same
    # data the renderer used), so the accounting stays artifact-derived
    # and fail-closed on any drift.
    iface_ph: dict[str, int] = {}
    if mi_doc is not None:
        for cls, shape in mi_shapes.items():
            if "primary_iface" in shape or "pattern_methods" not in shape:
                continue
            n = sum(1 for s in shape["pattern_methods"]
                    if isinstance(s, list))
            if n:
                iface_ph[mi_pattern_iface_name(cls)] = n
    for k, v in iface_ph.items():
        if hdr_ph_by_class.get(k) != v:
            print(f"emit_headers: ERROR  MI iface {k}: header has "
                  f"{hdr_ph_by_class.get(k, 0)} placeholders, mi-shape "
                  f"expects {v} (fail-closed)", file=sys.stderr)
            return 2
        # account for: remove from the strict cross-check below
        hdr_ph_by_class.pop(k, None)
    if hdr_ph_by_class != cls_ph_by_class:
        only_hdr = {k: v for k, v in hdr_ph_by_class.items()
                    if cls_ph_by_class.get(k) != v}
        only_cls = {k: v for k, v in cls_ph_by_class.items()
                    if hdr_ph_by_class.get(k) != v}
        print("emit_headers: ERROR  placeholder accounting mismatch "
              "between classification and emitted headers "
              "(fail-closed)", file=sys.stderr)
        for k, v in sorted(only_hdr.items()):
            print(f"    header-only {k}: {v} vs classification "
                  f"{cls_ph_by_class.get(k, 0)}", file=sys.stderr)
        for k, v in sorted(only_cls.items()):
            print(f"    classification-only {k}: {v} vs header "
                  f"{hdr_ph_by_class.get(k, 0)}", file=sys.stderr)
        return 2

    print(f"emit_headers: wrote {len(stats) + 3} files to {out_dir}")
    print(f"  fold-constraint solver: {len(override_votes)} (name,slot) "
          f"override-vote keys, {n_votes} total votes "
          f"(evidence: pinned vtable-slots.json singletons)")
    # v2 classification report: full-bound / placeholder-bound / rejected
    n_tab = len(v2_rows)
    full_bound = [r for r in v2_rows if r["mode"] == "bound"
                  and not r["placeholders"]]
    ph_bound = [r for r in v2_rows if r["mode"] == "bound"
                and r["placeholders"]]
    rejected = [r for r in v2_rows if r["mode"] == "rejected"]
    l2 = [r for r in v2_rows if r["mode"] == "l2"]
    n_ph = sum(len(r["placeholders"]) for r in ph_bound)
    print(f"  v2 contract: {n_tab} classes with tables -> "
          f"full-bound {len(full_bound)}, placeholder-bound {len(ph_bound)} "
          f"({n_ph} placeholders), rejected {len(rejected)}, "
          f"l2-deferred {len(l2)}")
    for r in rejected:
        if r["reason"] == "external_virtuals":
            print(f"    REJECTED {r['cls']:<26} external virtuals: "
                  f"{', '.join(r['external'][:6])}")
        else:
            print(f"    REJECTED {r['cls']:<26} vdtor-unplaced "
                  f"(no _E marker in {r.get('slots')} slots)")
    # W5 contract binding report (known-signature vs unbindable virtuals)
    n_cls = len(contract_rows)
    n_bound = sum(r["bound"] for r in contract_rows)
    n_unbound = sum(r["unbound"] for r in contract_rows)
    full = [r for r in contract_rows if r["unbound"] == 0]
    partial = [r for r in contract_rows if r["unbound"] > 0]
    print(f"  vtable contract: {n_cls} classes with primary vftables, "
          f"{len(full)} fully bound, {len(partial)} with unbindable "
          f"virtuals ({n_unbound} decls, kept in original order); "
          f"{n_bound} bound virtuals ordered by real slots")
    for r in partial:
        print(f"    {r['class']:<28} bound={r['bound']:3d} "
              f"unbound={r['unbound']:2d} "
              f"({', '.join(r['unbound_names'][:6])}"
              f"{'...' if len(r['unbound_names']) > 6 else ''})")
    for cls in classes:
        s = stats.get(cls)
        if not s:
            continue
        print(f"  {cls:<16} callables={s['methods']:4d} data={s['data']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
